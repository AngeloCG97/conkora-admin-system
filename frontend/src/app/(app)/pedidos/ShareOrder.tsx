'use client';

import LinkOffIcon from '@mui/icons-material/LinkOff';
import MoreVertIcon from '@mui/icons-material/MoreVert';
import RefreshIcon from '@mui/icons-material/Refresh';
import ShareIcon from '@mui/icons-material/Share';
import Button from '@mui/material/Button';
import IconButton from '@mui/material/IconButton';
import ListItemIcon from '@mui/material/ListItemIcon';
import Menu from '@mui/material/Menu';
import MenuItem from '@mui/material/MenuItem';
import Stack from '@mui/material/Stack';
import Typography from '@mui/material/Typography';
import { useMutation, useQuery, useQueryClient } from '@tanstack/react-query';
import { useState } from 'react';
import { useConfirm, useNotify } from '@/components/feedback/FeedbackProvider';
import { config } from '@/lib/config';
import { GraphQLRequestError, gqlRequest } from '@/lib/graphql';
import { shareLink, shareUrl } from '@/lib/share';

/**
 * Public link of a Pedido for its Cliente (issue #35). The token is generated by Postgres (`order_share`);
 * sharing again reuses it. "Generar enlace nuevo" replaces it (delete + insert in one transaction) and
 * "Desactivar enlace" deletes it, so the old link stops working (the public page answers 404).
 */

const SHARE_QUERY = `query OrderShare($id: uuid!) { order_share_by_pk(order_id: $id) { token } }`;
const CREATE_SHARE = `mutation CreateOrderShare($id: uuid!) { insert_order_share_one(object: { order_id: $id }) { token } }`;
const REGENERATE_SHARE = `mutation RegenerateOrderShare($id: uuid!) {
  delete_order_share_by_pk(order_id: $id) { order_id }
  insert_order_share_one(object: { order_id: $id }) { token }
}`;
const REVOKE_SHARE = `mutation RevokeOrderShare($id: uuid!) { delete_order_share_by_pk(order_id: $id) { order_id } }`;

type ShareRow = { token: string } | null;

export function ShareOrder({ orderId, customerName, cancelled }: { orderId: string; customerName: string; cancelled: boolean }) {
  const qc = useQueryClient();
  const notify = useNotify();
  const confirm = useConfirm();
  const [menuAnchor, setMenuAnchor] = useState<HTMLElement | null>(null);
  const [busy, setBusy] = useState(false);
  const queryKey = ['order-share', orderId];

  const share = useQuery({
    queryKey,
    queryFn: async () => (await gqlRequest<{ order_share_by_pk: ShareRow }>(SHARE_QUERY, { id: orderId })).order_share_by_pk,
  });
  const token = share.data?.token ?? null;

  /** Returns the existing token or creates the link (a concurrent creation is read back). */
  const ensureToken = async (): Promise<string> => {
    if (token) return token;
    try {
      const data = await gqlRequest<{ insert_order_share_one: { token: string } }>(CREATE_SHARE, { id: orderId });
      qc.setQueryData<ShareRow>(queryKey, data.insert_order_share_one);
      return data.insert_order_share_one.token;
    } catch (error) {
      if (!(error instanceof GraphQLRequestError && error.code === 'constraint-violation')) throw error;
      const { data: row } = await share.refetch();
      if (!row) throw error;
      return row.token;
    }
  };

  const onShare = async () => {
    setBusy(true);
    try {
      const url = shareUrl(window.location.origin, config.basePath, await ensureToken());
      const outcome = await shareLink(navigator, {
        title: 'Tu Venta en ConKora',
        text: `Hola ${customerName}, aquí puedes ver tu Venta de ConKora:`,
        url,
      });
      if (outcome === 'copied') notify.success('Enlace copiado');
      if (outcome === 'failed') notify.error('No se pudo compartir ni copiar el enlace');
    } catch {
      notify.error('No se pudo crear el enlace');
    } finally {
      setBusy(false);
    }
  };

  const regenerate = useMutation({
    mutationFn: () => gqlRequest<{ insert_order_share_one: { token: string } }>(REGENERATE_SHARE, { id: orderId }),
    onSuccess: (data) => {
      qc.setQueryData<ShareRow>(queryKey, data.insert_order_share_one);
      notify.success('Enlace nuevo generado; el anterior ya no funciona');
    },
    onError: () => notify.error('No se pudo generar el enlace nuevo'),
  });

  const revoke = useMutation({
    mutationFn: () => gqlRequest(REVOKE_SHARE, { id: orderId }),
    onSuccess: () => {
      qc.setQueryData<ShareRow>(queryKey, null);
      notify.success('Enlace desactivado');
    },
    onError: () => notify.error('No se pudo desactivar el enlace'),
  });

  const onRegenerate = async () => {
    setMenuAnchor(null);
    if (
      await confirm({
        title: '¿Generar un enlace nuevo?',
        message: 'El enlace que ya compartiste dejará de funcionar. Tendrás que compartir el nuevo.',
        confirmText: 'Generar enlace nuevo',
      })
    ) {
      regenerate.mutate();
    }
  };

  const onRevoke = async () => {
    setMenuAnchor(null);
    if (
      await confirm({
        title: '¿Desactivar el enlace?',
        message: 'El Cliente ya no podrá ver esta Venta con el enlace que le compartiste.',
        confirmText: 'Desactivar',
        danger: true,
      })
    ) {
      revoke.mutate();
    }
  };

  const working = busy || regenerate.isPending || revoke.isPending || share.isPending;

  return (
    <Stack spacing={0.5} sx={{ mb: 3 }}>
      <Stack direction="row" spacing={1} sx={{ alignItems: 'center' }}>
        <Button variant="contained" startIcon={<ShareIcon />} onClick={onShare} disabled={cancelled || working}>
          Compartir con el Cliente
        </Button>
        <IconButton aria-label="Opciones del enlace" onClick={(e) => setMenuAnchor(e.currentTarget)} disabled={!token || working}>
          <MoreVertIcon />
        </IconButton>
        <Menu anchorEl={menuAnchor} open={menuAnchor !== null} onClose={() => setMenuAnchor(null)}>
          <MenuItem onClick={onRegenerate} disabled={cancelled}>
            <ListItemIcon><RefreshIcon fontSize="small" /></ListItemIcon>
            Generar enlace nuevo
          </MenuItem>
          <MenuItem onClick={onRevoke}>
            <ListItemIcon><LinkOffIcon fontSize="small" color="error" /></ListItemIcon>
            Desactivar enlace
          </MenuItem>
        </Menu>
      </Stack>
      <Typography variant="body2" color="text.secondary">
        {cancelled
          ? 'Las Ventas canceladas no se pueden ver con el enlace.'
          : token
            ? 'Enlace activo: el Cliente ve esta Venta sin iniciar sesión.'
            : 'Envía un enlace para que el Cliente vea su Venta y su Saldo.'}
      </Typography>
    </Stack>
  );
}
